// Method untuk memformat angka menjadi Rupiah
private String formatRupiah(int angka) {
    String nilaiAngka = String.valueOf(angka);
    return "Rp " + nilaiAngka;
}

// Method untuk mengambil dan memvalidasi data transaksi
private int hitungTotal() {

    String nama = inputMakanDanMinum.getText().trim();
    String harga = inputHargaSatuan.getText().trim();
    String jumlah = inputJumlahBeli.getText().trim();

    // Validasi input kosong
    if (nama.isEmpty() || harga.isEmpty() || jumlah.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Semua data barang harus diisi!",
            "Peringatan",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return -1;
    }
    if (!harga.matches("[0-9]+") || !jumlah.matches("[0-9]+")) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Harga dan jumlah beli harus berupa angka!",
            "Input Tidak Valid",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );

        return -1;
    }
    int jumlahBeli = Integer.parseInt(jumlah);

        // Validasi jumlah pembelian
        if (jumlahBeli <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Jumlah pembelian harus lebih dari nol!",
                "Peringatan",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );

            return -1;
        }
        int hargaSatuan = Integer.parseInt(harga);
        int jumlahSatuanDibeli = Integer.parseInt(jumlah);
        int total = jumlahSatuanDibeli * hargaSatuan;

        return total;
}

