    private void btnHitungActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHitungActionPerformed
        // TODO add your handling code here:
         int total = hitungTotal();

    if (total != -1) {

        // Menampilkan total harga
        valueTotalHarga.setText(formatRupiah(total));
        inputKembalian.setText("");

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Total harga berhasil dihitung!",
            "Informasi",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );
    }
    }//GEN-LAST:event_btnHitungActionPerformed

    private void btnBayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBayarActionPerformed
        // TODO add your handling code here:
        int total = hitungTotal();

    if (total == -1) {
        return;
    }

    String pembayaran = inputBayar.getText().trim();
    // Validasi pembayaran kosong
    if (pembayaran.isEmpty() || !pembayaran.matches("[0-9]+")) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Masukkan uang pembayaran terlebih dahulu! dan berupa angka",
            "Peringatan",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }
    // Menampilkan total harga
        int uangBayar = Integer.parseInt(pembayaran);
        valueTotalHarga.setText(formatRupiah(total));

        if (uangBayar < total) {

            int kekurangan = total - uangBayar;
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Pembayaran kurang sebesar "
                + formatRupiah(kekurangan),
                "Pembayaran Kurang",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            inputKembalian.setText("");
            inputBayar.setText("");
            return;
        }

        // Menghitung uang kembalian
        int kembalian = uangBayar - total;

        inputKembalian.setText(formatRupiah(kembalian));

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Total Harga: " + formatRupiah(total) + "\nUang Dibayar: " + formatRupiah(uangBayar) + "\nUang Kembalian: " + formatRupiah(kembalian),
            "Transaksi Berhasil",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );
    }//GEN-LAST:event_btnBayarActionPerformed

